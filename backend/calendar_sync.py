"""
Study Planner & Google Calendar Integration Engine
Generates balanced AIR-1 study timetables (JEE Advanced + CBSE 12th Board 95%+),
creates 1-click Google Calendar sync links, and exports standard .ics calendar files.
"""

import urllib.parse
from datetime import datetime, timedelta
from .database import get_db

def create_google_calendar_url(title, start_dt, end_dt, details="", location="Study Desk"):
    """
    Constructs a direct 1-click Google Calendar event URL.
    Format of dates in Google Calendar URL: YYYYMMDDTHHmmSSZ
    """
    # Assuming local time format YYYY-MM-DD HH:MM
    try:
        s_obj = datetime.strptime(start_dt, "%Y-%m-%d %H:%M")
        e_obj = datetime.strptime(end_dt, "%Y-%m-%d %H:%M")
        s_str = s_obj.strftime("%Y%m%dT%H%M00")
        e_str = e_obj.strftime("%Y%m%dT%H%M00")
    except Exception:
        # Fallback date formatting
        clean_s = start_dt.replace("-", "").replace(" ", "T").replace(":", "") + "00"
        clean_e = end_dt.replace("-", "").replace(" ", "T").replace(":", "") + "00"
        s_str = clean_s
        e_str = clean_e

    base_url = "https://calendar.google.com/calendar/render"
    params = {
        "action": "TEMPLATE",
        "text": f"🎯 [AIR-1 JEE] {title}",
        "dates": f"{s_str}/{e_str}",
        "details": details + "\n\nGenerated by JEE Advanced AIR-1 App AI Planner.",
        "location": location
    }
    return f"{base_url}?{urllib.parse.urlencode(params)}"

def generate_ics_calendar():
    """Generates an RFC 5545 compliant .ics calendar file for all scheduled study blocks and tests."""
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM calendar_events ORDER BY start_time ASC")
    events = cursor.fetchall()

    # Also fetch upcoming school tests
    cursor.execute("SELECT * FROM school_tests WHERE status = 'upcoming' ORDER BY test_date ASC")
    school_tests = cursor.fetchall()

    # Also fetch external test series
    cursor.execute("SELECT * FROM test_series_registry ORDER BY scheduled_date ASC")
    test_series = cursor.fetchall()
    conn.close()

    lines = [
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//JEE Advanced AIR-1 App//Planner//EN",
        "CALSCALE:GREGORIAN",
        "METHOD:PUBLISH",
        "X-WR-CALNAME:JEE Advanced AIR-1 & CBSE 95% Schedule",
        "X-WR-TIMEZONE:Asia/Kolkata"
    ]

    for ev in events:
        ev_dict = dict(ev)
        s_str = ev_dict["start_time"].replace("-", "").replace(" ", "T").replace(":", "") + "00"
        e_str = ev_dict["end_time"].replace("-", "").replace(" ", "T").replace(":", "") + "00"
        lines.extend([
            "BEGIN:VEVENT",
            f"UID:event-{ev_dict['id']}@jeeair1.app",
            f"DTSTAMP:{datetime.utcnow().strftime('%Y%m%dT%H%M%SZ')}",
            f"DTSTART:{s_str}",
            f"DTEND:{e_str}",
            f"SUMMARY:[AIR-1 Plan] {ev_dict['title']}",
            f"DESCRIPTION:{ev_dict.get('description', '')}",
            "STATUS:CONFIRMED",
            "END:VEVENT"
        ])

    for st in school_tests:
        st_dict = dict(st)
        d_str = st_dict["test_date"].replace("-", "")
        lines.extend([
            "BEGIN:VEVENT",
            f"UID:school-{st_dict['id']}@jeeair1.app",
            f"DTSTAMP:{datetime.utcnow().strftime('%Y%m%dT%H%M%SZ')}",
            f"DTSTART;VALUE=DATE:{d_str}",
            f"SUMMARY:🏫 [12th Board] {st_dict['test_title']} ({st_dict['subject']})",
            f"DESCRIPTION:Syllabus: {st_dict.get('syllabus', '')}. Aim for 95%+ presentation.",
            "STATUS:CONFIRMED",
            "END:VEVENT"
        ])

    for ts in test_series:
        ts_dict = dict(ts)
        d_str = ts_dict["scheduled_date"].replace("-", "")
        lines.extend([
            "BEGIN:VEVENT",
            f"UID:series-{ts_dict['id']}@jeeair1.app",
            f"DTSTAMP:{datetime.utcnow().strftime('%Y%m%dT%H%M%SZ')}",
            f"DTSTART;VALUE=DATE:{d_str}",
            f"SUMMARY:📝 [Mock Test] {ts_dict['series_name']} #{ts_dict['test_number']}",
            f"DESCRIPTION:Exam Type: {ts_dict.get('exam_type')}. Notes: {ts_dict.get('notes', '')}",
            "STATUS:CONFIRMED",
            "END:VEVENT"
        ])

    lines.append("END:VCALENDAR")
    return "\r\n".join(lines)

def get_study_calendar_events():
    """Fetches calendar events with direct Google Calendar links."""
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM calendar_events ORDER BY start_time ASC")
    rows = cursor.fetchall()
    conn.close()

    result = []
    for r in rows:
        d = dict(r)
        d["google_calendar_url"] = create_google_calendar_url(
            d["title"], d["start_time"], d["end_time"], d.get("description", "")
        )
        result.append(d)
    return result

def add_calendar_event(title, event_type, start_time, end_time, description=""):
    """Adds a new study or mock test event."""
    conn = get_db()
    cursor = conn.cursor()
    cursor.execute("""
    INSERT INTO calendar_events (title, event_type, start_time, end_time, description)
    VALUES (?, ?, ?, ?, ?)
    """, (title, event_type, start_time, end_time, description))
    conn.commit()
    new_id = cursor.lastrowid
    conn.close()

    gcal_url = create_google_calendar_url(title, start_time, end_time, description)
    return {
        "status": "success",
        "event_id": new_id,
        "google_calendar_url": gcal_url
    }
